// Android app-language wiring, checked as text: no Gradle, no emulator. The
// manifest points at the per-app language list, the generated list carries
// exactly the registry codes in order, the bundle ships every language in the
// base APK, the packed resources are limited to the four shipped locales, and
// every notification string the host service reads really exists.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { equal, finish, ok, ROOT, section } from "./harness.mjs";

function read(rel) {
  return readFileSync(join(ROOT, rel), "utf8");
}

section("manifest and per-app language list");

const manifest = read("android/app/src/main/AndroidManifest.xml");
ok(
  "manifest declares android:localeConfig",
  manifest.includes('android:localeConfig="@xml/locales_config"'),
);

const registry = JSON.parse(read("i18n/locales.json")).map((locale) => locale.code);
let config = "";
try {
  config = read("android/app/src/main/res/xml/locales_config.xml");
} catch {
  ok("locales_config.xml exists (run npm run i18n:build first)", false);
}
if (config) {
  ok("locales_config marks itself generated", config.includes("Generated by scripts/i18n.mjs"));
  const listed = [...config.matchAll(/<locale android:name="([^"]+)"/g)].map((m) => m[1]);
  equal("locales_config lists exactly the registry codes", JSON.stringify(listed), JSON.stringify(registry));
}

section("bundle and resource packaging");

const gradle = read("android/app/build.gradle.kts");
ok(
  "language split is disabled",
  /bundle\s*\{\s*language\s*\{\s*enableSplit\s*=\s*false/.test(gradle),
);
const filters = gradle.match(/localeFilters\s*\+=\s*listOf\(([^)]*)\)/);
ok("localeFilters names the four shipped locales", filters != null);
equal(
  "localeFilters holds en, ar, pt-rBR and b+es+419",
  filters ? filters[1].match(/"[^"]+"/g)?.join(",") ?? "" : "",
  '"en","ar","pt-rBR","b+es+419"',
);

section("Kotlin side");

const uiPrefs = read("android/app/src/main/java/net/leviro/levix/UiPrefs.kt");
const languages = uiPrefs.match(/val LANGUAGES\s*=\s*listOf\(([^)]*)\)/);
ok("UiPrefs declares LANGUAGES", languages != null);
equal(
  "UiPrefs.LANGUAGES equals the registry codes",
  languages ? languages[1].match(/"[^"]+"/g)?.join(",") ?? "" : "",
  registry.map((code) => `"${code}"`).join(","),
);

const service = read("android/app/src/main/java/net/leviro/levix/LevixHostService.kt");
const english = JSON.parse(read("i18n/en/android.json"));
const available = new Set(Object.keys(english));
const used = [...service.matchAll(/R\.string\.([A-Za-z0-9_]+)/g)].map((m) => m[1]);
for (const name of [...new Set(used)].sort()) {
  ok(`host notification string "${name}" exists in en/android.json`, available.has(name));
}

finish();
