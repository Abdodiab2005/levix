// Catalog generator and validator.
//
// English is the source locale. `translations.ts` lists every registry locale.
// The `ar` object stays before the `en` binding, and a locale with no
// dashboard.json is an empty object. The gateway dictionary and the Node
// catalog follow locales.json order. Android plural tokens are compared as a
// multiset union: the count of a token is the most times it appears in any one
// category, so a locale with more categories still matches when each category
// carries the same tokens.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const GENERATED_BY = "Generated by scripts/i18n.mjs from i18n/. Do not edit.";
export const GATEWAY_START = "// <i18n:generated>";
export const GATEWAY_END = "// </i18n:generated>";

const SOURCE = "en";
const DASHBOARD_FIRST = ["ar", "en"];
const FILE_ORDER = ["dashboard", "gateway", "android", "commands"];
const LOCALE_FIELDS = ["code", "name", "dir", "android", "required"];
const REVIEW_FIELDS = ["status", "by", "date", "sha256"];
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const PLACEHOLDER = /\{([A-Za-z_][A-Za-z0-9_]*)\}/g;
const ANDROID_TOKEN = /%\d+\$[a-zA-Z]/g;
const MARKUP = /<[A-Za-z/!]/;
const TAG = /<\/?([A-Za-z][A-Za-z0-9]*)\b[^>]*>/g;

function problem(file, key, text) {
  return { file, key, message: key ? `${file} ${key}: ${text}` : `${file}: ${text}` };
}

function isPlain(value) {
  return Boolean(value) && typeof value === "object" && !Array.isArray(value);
}

function localeEntries(catalog) {
  if (!Array.isArray(catalog.locales)) return [];
  return catalog.locales.filter((locale) => locale && typeof locale.code === "string");
}

function fileMap(bundle) {
  const map = new Map();
  if (!isPlain(bundle)) return map;
  for (const id of FILE_ORDER) {
    if (bundle[id] !== undefined) map.set(id, bundle[id]);
  }
  if (isPlain(bundle.bot)) {
    for (const area of Object.keys(bundle.bot).sort()) map.set(`bot/${area}`, bundle.bot[area]);
  }
  return map;
}

export function dashboardLocales(catalog) {
  const present = new Set();
  for (const locale of localeEntries(catalog)) {
    if (catalog.bundles?.[locale.code]?.dashboard !== undefined) present.add(locale.code);
  }
  const ordered = [];
  for (const code of DASHBOARD_FIRST) if (present.has(code)) ordered.push(code);
  for (const locale of localeEntries(catalog)) {
    if (present.has(locale.code) && !DASHBOARD_FIRST.includes(locale.code)) {
      ordered.push(locale.code);
    }
  }
  return ordered;
}

export function gatewayLocales(catalog) {
  return localeEntries(catalog)
    .filter((locale) => catalog.bundles?.[locale.code]?.gateway !== undefined)
    .map((locale) => locale.code);
}

function hasNodeMessages(bundle) {
  if (!bundle) return false;
  if (bundle.commands !== undefined) return true;
  return isPlain(bundle.bot) && Object.keys(bundle.bot).length > 0;
}

export function nodeLocales(catalog) {
  return localeEntries(catalog)
    .filter((locale) => locale.required || hasNodeMessages(catalog.bundles?.[locale.code]))
    .map((locale) => locale.code);
}

function nodeMessages(bundle) {
  const out = {};
  if (!bundle) return out;
  if (isPlain(bundle.commands)) {
    for (const [key, value] of Object.entries(bundle.commands)) out[`commands.${key}`] = value;
  }
  if (isPlain(bundle.bot)) {
    for (const area of Object.keys(bundle.bot).sort()) {
      const messages = bundle.bot[area];
      if (!isPlain(messages)) continue;
      for (const [key, value] of Object.entries(messages)) out[`bot.${area}.${key}`] = value;
    }
  }
  return out;
}

function renderJs(value, indent) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  if (value === null || value === undefined) return "null";
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const pad = " ".repeat(indent);
    const inner = " ".repeat(indent + 2);
    const lines = value.map((item) => `${inner}${renderJs(item, indent + 2)},`);
    return `[\n${lines.join("\n")}\n${pad}]`;
  }
  const keys = Object.keys(value);
  if (keys.length === 0) return "{}";
  const pad = " ".repeat(indent);
  const inner = " ".repeat(indent + 2);
  const lines = keys.map((key) => {
    const rendered = IDENT.test(key) ? key : JSON.stringify(key);
    return `${inner}${rendered}: ${renderJs(value[key], indent + 2)},`;
  });
  return `{\n${lines.join("\n")}\n${pad}}`;
}

function jsKey(code) {
  return IDENT.test(code) ? code : JSON.stringify(code);
}

function translationOrder(catalog) {
  const codes = localeEntries(catalog).map((locale) => locale.code);
  const ordered = [];
  for (const code of DASHBOARD_FIRST) {
    if (codes.includes(code)) ordered.push(code);
  }
  for (const code of codes) {
    if (!ordered.includes(code)) ordered.push(code);
  }
  return ordered;
}

function dashboardMessages(catalog, code) {
  const dashboard = catalog.bundles?.[code]?.dashboard;
  return isPlain(dashboard) ? dashboard : {};
}

export function renderTranslations(catalog) {
  const registry = localeEntries(catalog);
  const codes = registry.map((locale) => locale.code);
  const type = codes.length ? codes.map((code) => JSON.stringify(code)).join(" | ") : "never";
  const order = translationOrder(catalog);
  const typeFields = order.map((code) => {
    const field =
      code === SOURCE ? "Record<MessageKey, string>" : "Partial<Record<MessageKey, string>>";
    return `  ${jsKey(code)}: ${field};`;
  });
  const valueLines = order.map((code) => {
    if (code === SOURCE) return "  en,";
    const messages = dashboardMessages(catalog, code);
    const rendered = Object.keys(messages).length ? renderJs(messages, 2) : "{}";
    return `  ${jsKey(code)}: ${rendered},`;
  });
  const localeLines = registry.map((locale) => {
    const dir = locale.dir === "rtl" ? "rtl" : "ltr";
    const name = typeof locale.name === "string" ? locale.name : locale.code;
    return `  { code: ${JSON.stringify(locale.code)}, name: ${JSON.stringify(name)}, dir: ${JSON.stringify(dir)} },`;
  });
  return (
    `// ${GENERATED_BY}\n\n` +
    `export type Language = ${type};\n\n` +
    `const en = ${renderJs(dashboardMessages(catalog, SOURCE), 0)};\n\n` +
    `export type MessageKey = keyof typeof en;\n\n` +
    `export const translations: {\n` +
    `${typeFields.join("\n")}\n` +
    `} = {\n` +
    `${valueLines.join("\n")}\n` +
    `};\n\n` +
    `export const LOCALES: { code: Language; name: string; dir: "ltr" | "rtl" }[] = [\n` +
    `${localeLines.join("\n")}\n` +
    `];\n`
  );
}

export function renderGatewayDict(catalog) {
  const obj = {};
  for (const code of gatewayLocales(catalog)) obj[code] = catalog.bundles[code].gateway;
  return `  // ${GENERATED_BY}\n  var DICT = ${renderJs(obj, 2)};`;
}

export function applyGatewayMarkers(source, dict) {
  const start = source.indexOf(GATEWAY_START);
  const end = source.indexOf(GATEWAY_END);
  if (start < 0 || end < 0 || end < start) {
    throw new Error("public/gateway-i18n.js is missing the i18n generation markers");
  }
  const startLineEnd = source.indexOf("\n", start);
  const endLineStart = source.lastIndexOf("\n", end);
  if (startLineEnd < 0 || endLineStart < startLineEnd) {
    throw new Error("public/gateway-i18n.js generation markers must be on their own lines");
  }
  return `${source.slice(0, startLineEnd + 1)}${dict}\n${source.slice(endLineStart + 1)}`;
}

export function escapeAndroidString(value) {
  let out = "";
  for (const ch of value) {
    if (ch === "\\") out += "\\\\";
    else if (ch === "'") out += "\\'";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\t") out += "\\t";
    else if (ch === "\r") out += "\\r";
    else if (ch === "&") out += "&amp;";
    else if (ch === "<") out += "&lt;";
    else if (ch === ">") out += "&gt;";
    else out += ch;
  }
  out = escapeAndroidPercents(out);
  if (value.startsWith("@") || value.startsWith("?")) out = `\\${out}`;
  if (value.startsWith(" ") || value.endsWith(" ")) out = `"${out}"`;
  return out;
}

function escapeAndroidPercents(value) {
  let out = "";
  for (let i = 0; i < value.length; i += 1) {
    if (value[i] !== "%") {
      out += value[i];
      continue;
    }
    const token = /^%\d+\$[a-zA-Z]/.exec(value.slice(i));
    if (token) {
      out += token[0];
      i += token[0].length - 1;
      continue;
    }
    out += "%%";
  }
  return out;
}

function escapeAttr(value) {
  return value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
}

function escapeComment(value) {
  return value.replace(/--/g, "- -");
}

export function renderAndroidXml(catalog, code) {
  const messages = catalog.bundles?.[code]?.android;
  if (!isPlain(messages)) throw new Error(`no android messages for ${code}`);
  const notes = code === SOURCE && isPlain(catalog.notes?.android) ? catalog.notes.android : {};
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${GENERATED_BY} -->`,
    "<resources>",
  ];
  for (const [key, value] of Object.entries(messages)) {
    if (typeof notes[key] === "string" && notes[key] !== "") {
      lines.push(`    <!-- ${escapeComment(notes[key])} -->`);
    }
    if (isPlain(value)) {
      lines.push(`    <plurals name="${escapeAttr(key)}">`);
      for (const [quantity, text] of Object.entries(value)) {
        const body = typeof text === "string" ? escapeAndroidString(text) : "";
        lines.push(`        <item quantity="${escapeAttr(quantity)}">${body}</item>`);
      }
      lines.push("    </plurals>");
    } else {
      const body = typeof value === "string" ? escapeAndroidString(value) : "";
      lines.push(`    <string name="${escapeAttr(key)}">${body}</string>`);
    }
  }
  lines.push("</resources>");
  return `${lines.join("\n")}\n`;
}

function androidRel(locale) {
  return `android/app/src/main/res/${locale.android}/strings.xml`;
}

export function renderNodeCatalog(catalog) {
  const messages = {};
  for (const code of nodeLocales(catalog)) messages[code] = nodeMessages(catalog.bundles?.[code]);
  const data = {
    locales: localeEntries(catalog).map((locale) => ({
      code: locale.code,
      name: locale.name,
      dir: locale.dir,
      android: locale.android,
      required: locale.required,
    })),
    messages,
  };
  return `// ${GENERATED_BY}\nmodule.exports = Object.freeze(${renderJs(data, 0)});\n`;
}

export function renderGenerated(catalog, gatewaySource) {
  const files = {};
  if (dashboardLocales(catalog).length) {
    files["frontend/src/i18n/translations.ts"] = renderTranslations(catalog);
  }
  if (gatewayLocales(catalog).length) {
    if (typeof gatewaySource !== "string") throw new Error("public/gateway-i18n.js is missing");
    files["public/gateway-i18n.js"] = applyGatewayMarkers(
      gatewaySource,
      renderGatewayDict(catalog),
    );
  }
  for (const locale of localeEntries(catalog)) {
    const android = catalog.bundles?.[locale.code]?.android;
    const folder = locale.android;
    if (android !== undefined && typeof folder === "string") {
      files[androidRel(locale)] = renderAndroidXml(catalog, locale.code);
    }
  }
  files["src/i18n/catalog.generated.cjs"] = renderNodeCatalog(catalog);
  return files;
}

function validateLocales(locales) {
  const errors = [];
  if (!Array.isArray(locales)) return [problem("locales.json", "", "must be an array")];
  const codes = new Set();
  const folders = new Set();
  let rtl = 0;
  for (let index = 0; index < locales.length; index += 1) {
    const locale = locales[index];
    const at = `locales.json[${index}]`;
    if (!isPlain(locale)) {
      errors.push(problem(at, "", "must be an object"));
      continue;
    }
    for (const field of LOCALE_FIELDS) {
      if (!Object.hasOwn(locale, field)) errors.push(problem(at, field, "missing field"));
    }
    for (const field of Object.keys(locale)) {
      if (!LOCALE_FIELDS.includes(field)) errors.push(problem(at, field, "unknown field"));
    }
    if (typeof locale.code !== "string" || locale.code === "") {
      errors.push(problem(at, "code", "must be a non-empty string"));
    } else if (codes.has(locale.code)) {
      errors.push(problem(at, "code", `duplicate code "${locale.code}"`));
    } else {
      codes.add(locale.code);
    }
    if (typeof locale.name !== "string" || locale.name === "") {
      errors.push(problem(at, "name", "must be a non-empty string"));
    }
    if (locale.dir !== "ltr" && locale.dir !== "rtl") {
      errors.push(problem(at, "dir", 'must be "ltr" or "rtl"'));
    }
    if (locale.dir === "rtl") rtl += 1;
    if (typeof locale.android !== "string" || locale.android === "") {
      errors.push(problem(at, "android", "must be a non-empty string"));
    } else if (folders.has(locale.android)) {
      errors.push(problem(at, "android", `duplicate folder "${locale.android}"`));
    } else {
      folders.add(locale.android);
    }
    if (typeof locale.required !== "boolean") {
      errors.push(problem(at, "required", "must be a boolean"));
    }
  }
  if (rtl > 1) errors.push(problem("locales.json", "", "more than one rtl locale"));
  if (!codes.has(SOURCE)) errors.push(problem("locales.json", SOURCE, "source locale is missing"));
  return errors;
}

function englishFile(bundles, file) {
  const source = bundles[SOURCE];
  if (!isPlain(source)) return null;
  if (FILE_ORDER.includes(file)) return isPlain(source[file]) ? source[file] : null;
  if (file.startsWith("bot/")) {
    const area = file.slice(4);
    return isPlain(source.bot?.[area]) ? source.bot[area] : null;
  }
  if (file === "commands") return isPlain(source.commands) ? source.commands : null;
  return null;
}

function validateNotes(notes, bundles) {
  if (notes === undefined) return [];
  if (!isPlain(notes)) return [problem("notes.json", "", "must be an object")];
  const errors = [];
  for (const [file, entries] of Object.entries(notes)) {
    if (!isPlain(entries)) {
      errors.push(problem("notes.json", file, "must be an object"));
      continue;
    }
    const english = englishFile(bundles, file);
    for (const [key, note] of Object.entries(entries)) {
      if (!english || !Object.hasOwn(english, key)) {
        errors.push(problem("notes.json", `${file}.${key}`, "key is not in the English file"));
      } else if (typeof note !== "string") {
        errors.push(problem("notes.json", `${file}.${key}`, "note must be a string"));
      }
    }
  }
  return errors;
}

function validateReview(review) {
  if (review === undefined) return [];
  if (!isPlain(review)) return [problem("review.json", "", "must be an object")];
  const errors = [];
  for (const [key, entry] of Object.entries(review)) {
    if (!/^[^/]+\/[^/].*$/.test(key)) {
      errors.push(problem("review.json", key, 'key must be "<locale>/<file>"'));
    }
    if (!isPlain(entry)) {
      errors.push(problem("review.json", key, "must be an object"));
      continue;
    }
    for (const field of Object.keys(entry)) {
      if (!REVIEW_FIELDS.includes(field)) {
        errors.push(problem("review.json", key, `unknown field "${field}"`));
      }
    }
    if (entry.status !== "draft" && entry.status !== "reviewed") {
      errors.push(problem("review.json", key, 'status must be "draft" or "reviewed"'));
    }
    for (const field of ["by", "date", "sha256"]) {
      if (typeof entry[field] !== "string" || entry[field] === "") {
        errors.push(problem("review.json", key, `${field} must be a non-empty string`));
      }
    }
  }
  return errors;
}

function isJsonWs(ch) {
  return ch === " " || ch === "\n" || ch === "\r" || ch === "\t";
}

export function jsonDuplicateKeys(text) {
  const duplicates = [];
  let i = 0;
  const fail = (message) => {
    throw new Error(`${message} at ${i}`);
  };
  const skipWs = () => {
    while (i < text.length && isJsonWs(text[i])) i += 1;
  };
  const readString = () => {
    if (text[i] !== '"') fail("expected string");
    i += 1;
    let out = "";
    while (i < text.length) {
      const ch = text[i];
      if (ch === '"') {
        i += 1;
        return out;
      }
      if (ch === "\\") {
        const next = text[i + 1];
        const simple = {
          '"': '"',
          "\\": "\\",
          "/": "/",
          b: "\b",
          f: "\f",
          n: "\n",
          r: "\r",
          t: "\t",
        };
        if (next === "u") {
          const hex = text.slice(i + 2, i + 6);
          if (!/^[0-9a-fA-F]{4}$/.test(hex)) fail("bad unicode escape");
          out += String.fromCharCode(Number.parseInt(hex, 16));
          i += 6;
          continue;
        }
        if (!(next in simple)) fail("bad escape");
        out += simple[next];
        i += 2;
        continue;
      }
      if (ch < " ") fail("control character in string");
      out += ch;
      i += 1;
    }
    fail("unterminated string");
  };
  const readLiteral = () => {
    const start = i;
    while (i < text.length && !isJsonWs(text[i]) && !",]}".includes(text[i])) i += 1;
    if (i === start) fail("expected value");
  };
  const parseValue = (path) => {
    skipWs();
    const ch = text[i];
    if (ch === "{") return parseObject(path);
    if (ch === "[") return parseArray(path);
    if (ch === '"') {
      readString();
      return;
    }
    if (ch === "-" || (ch >= "0" && ch <= "9") || ch === "t" || ch === "f" || ch === "n") {
      readLiteral();
      return;
    }
    fail("expected value");
  };
  const parseObject = (path) => {
    i += 1;
    const seen = new Set();
    skipWs();
    if (text[i] === "}") {
      i += 1;
      return;
    }
    while (i < text.length) {
      skipWs();
      const key = readString();
      const keyPath = path.length ? `${path.join(".")}.${key}` : key;
      if (seen.has(key)) duplicates.push(keyPath);
      seen.add(key);
      skipWs();
      if (text[i] !== ":") fail("expected colon");
      i += 1;
      parseValue(path.concat(key));
      skipWs();
      if (text[i] === ",") {
        i += 1;
        skipWs();
        if (text[i] === "}") fail("trailing comma");
        continue;
      }
      if (text[i] === "}") {
        i += 1;
        return;
      }
      fail("expected comma or end of object");
    }
    fail("unterminated object");
  };
  const parseArray = (path) => {
    i += 1;
    skipWs();
    if (text[i] === "]") {
      i += 1;
      return;
    }
    let index = 0;
    while (i < text.length) {
      parseValue(path.concat(String(index)));
      index += 1;
      skipWs();
      if (text[i] === ",") {
        i += 1;
        skipWs();
        if (text[i] === "]") fail("trailing comma");
        continue;
      }
      if (text[i] === "]") {
        i += 1;
        return;
      }
      fail("expected comma or end of array");
    }
    fail("unterminated array");
  };
  skipWs();
  parseValue([]);
  skipWs();
  if (i !== text.length) fail("trailing junk");
  return duplicates;
}

function scanRaw(rawTexts) {
  const errors = [];
  for (const [file, text] of Object.entries(rawTexts)) {
    if (typeof text !== "string") continue;
    try {
      for (const key of jsonDuplicateKeys(text)) errors.push(problem(file, key, "duplicate key"));
    } catch (error) {
      errors.push(problem(file, "", `invalid JSON (${error.message})`));
    }
  }
  return errors;
}

function textsOf(value) {
  if (typeof value === "string") return [value];
  if (!isPlain(value)) return [];
  return Object.values(value).filter((item) => typeof item === "string");
}

function placeholderSet(value) {
  const names = new Set();
  for (const text of textsOf(value)) {
    for (const match of text.matchAll(PLACEHOLDER)) names.add(match[1]);
  }
  return names;
}

function countTokens(text) {
  const counts = new Map();
  for (const match of text.matchAll(ANDROID_TOKEN)) {
    counts.set(match[0], (counts.get(match[0]) || 0) + 1);
  }
  return counts;
}

function tokenBag(value) {
  if (typeof value === "string") return countTokens(value);
  const bag = new Map();
  if (!isPlain(value)) return bag;
  for (const text of Object.values(value)) {
    if (typeof text !== "string") continue;
    for (const [token, count] of countTokens(text)) {
      bag.set(token, Math.max(bag.get(token) || 0, count));
    }
  }
  return bag;
}

function bagsEqual(left, right) {
  if (left.size !== right.size) return false;
  for (const [key, count] of left) if (right.get(key) !== count) return false;
  return true;
}

function setsEqual(left, right) {
  if (left.size !== right.size) return false;
  for (const key of left) if (!right.has(key)) return false;
  return true;
}

function formatDiff(got, want, wrap) {
  const missing = [];
  const extra = [];
  const keys = [...new Set([...got.keys(), ...want.keys()])].sort();
  for (const key of keys) {
    const have = got.get(key) || 0;
    const need = want.get(key) || 0;
    const label = wrap ? wrap(key) : key;
    if (have < need) missing.push(need - have === 1 ? label : `${label} x${need - have}`);
    if (have > need) extra.push(have - need === 1 ? label : `${label} x${have - need}`);
  }
  const parts = [];
  if (missing.length) parts.push(`missing ${missing.join(", ")}`);
  if (extra.length) parts.push(`extra ${extra.join(", ")}`);
  return parts.join("; ");
}

function formatSetDiff(got, want) {
  const gotBag = new Map([...got].map((key) => [key, 1]));
  const wantBag = new Map([...want].map((key) => [key, 1]));
  return formatDiff(gotBag, wantBag, (key) => `{${key}}`);
}

function tagSet(text) {
  const names = new Set();
  for (const match of text.matchAll(TAG)) names.add(match[1].toLowerCase());
  return names;
}

function markupIssues(text, allowed) {
  if (!allowed) return MARKUP.test(text) ? ["contains markup"] : [];
  const issues = [];
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] !== "<" || !/[A-Za-z/!]/.test(text[i + 1] || "")) continue;
    const match = /^<\/?([A-Za-z][A-Za-z0-9]*)\b[^>]*>/.exec(text.slice(i));
    if (!match) {
      issues.push("contains markup");
      break;
    }
    if (!allowed.has(match[1].toLowerCase())) {
      issues.push(`tag "${match[1]}" is not in the English value`);
    }
    i += match[0].length - 1;
  }
  return issues;
}

function countChar(value, ch) {
  let count = 0;
  for (const text of textsOf(value)) {
    for (const item of text) if (item === ch) count += 1;
  }
  return count;
}

function validateBundle(catalog, errors, warnings) {
  const bundles = catalog.bundles || {};
  const htmlKeys = new Set(catalog.htmlKeys || []);
  const cache = new Map();
  const reported = new Set();
  const sourceFiles = fileMap(bundles[SOURCE]);

  const categoriesFor = (code, label) => {
    if (!cache.has(code)) {
      try {
        cache.set(code, new Set(new Intl.PluralRules(code).resolvedOptions().pluralCategories));
      } catch {
        cache.set(code, null);
      }
    }
    const categories = cache.get(code);
    if (!categories && !reported.has(code)) {
      reported.add(code);
      errors.push(problem(label, "", `locale ${code} is not supported by Intl.PluralRules`));
    }
    return categories;
  };

  const allowedTags = (id, key, english) => {
    if (id !== "gateway" || !htmlKeys.has(key)) return null;
    return tagSet(typeof english === "string" ? english : "");
  };

  const checkValue = (label, id, key, code, value, english) => {
    if (typeof value !== "string" && !isPlain(value)) {
      errors.push(problem(label, key, "value must be a string"));
      return;
    }
    if (isPlain(value)) {
      // Android uses positional tokens. commands and bot use {name}, and t()
      // picks a category with Intl.PluralRules. Dashboard and gateway stay strings.
      const nodePlural = id === "commands" || id.startsWith("bot/");
      if (id !== "android" && !nodePlural) {
        const where = "android, commands, and bot";
        errors.push(problem(label, key, `plural value is only valid in ${where}`));
        return;
      }
      if (!Object.hasOwn(value, "other")) {
        errors.push(problem(label, key, 'plural is missing "other"'));
      }
      const categories = categoriesFor(code, label);
      for (const [category, text] of Object.entries(value)) {
        if (categories && !categories.has(category)) {
          errors.push(problem(label, key, `category "${category}" is not valid for ${code}`));
        }
        if (typeof text !== "string") {
          errors.push(problem(label, key, `category "${category}" must be a string`));
        } else if (text === "") {
          errors.push(problem(label, key, `category "${category}" is empty`));
        } else {
          for (const issue of markupIssues(text, allowedTags(id, key, english))) {
            errors.push(problem(label, key, issue));
          }
        }
      }
      if (nodePlural && isPlain(english)) {
        const wantNames = placeholderSet(english);
        const other = typeof english.other === "string" ? english.other : "";
        for (const [category, text] of Object.entries(value)) {
          if (typeof text !== "string" || text === "") continue;
          const gotNames = placeholderSet(text);
          if (!setsEqual(gotNames, wantNames)) {
            const detail = formatSetDiff(gotNames, wantNames) || "different";
            errors.push(problem(label, key, `placeholders do not match en (${detail})`));
          }
          for (const ch of ["*", "`"]) {
            const want = countChar(other, ch);
            const got = countChar(text, ch);
            if (want === got) continue;
            const note = `"${ch}" count ${got} does not match en (${want})`;
            errors.push(problem(label, key, `category "${category}" ${note}`));
          }
        }
      }
      return;
    }
    if (value === "") errors.push(problem(label, key, "empty string"));
    else if (id !== "commands" && !id.startsWith("bot/")) {
      // Command usage contains literal CLI placeholders such as <member>.
      // These Node messages are sent as WhatsApp text, not rendered as HTML.
      for (const issue of markupIssues(value, allowedTags(id, key, english))) {
        errors.push(problem(label, key, issue));
      }
    }
  };

  const compareValue = (label, id, key, source, theirs) => {
    const sourcePlural = isPlain(source);
    const theirPlural = isPlain(theirs);
    const sameKind = (typeof source === "string") === (typeof theirs === "string");
    const sameShape = sameKind && sourcePlural === theirPlural;
    if (!sameShape) {
      errors.push(problem(label, key, sourcePlural ? "expected a plural" : "expected a string"));
      return;
    }
    if (id === "android") {
      const want = tokenBag(source);
      const got = tokenBag(theirs);
      if (!bagsEqual(want, got)) {
        errors.push(
          problem(
            label,
            key,
            `positional tokens do not match en (${formatDiff(got, want) || "different"})`,
          ),
        );
      }
      return;
    }
    if (typeof source === "string" && typeof theirs === "string") {
      const want = placeholderSet(source);
      const got = placeholderSet(theirs);
      if (!setsEqual(want, got)) {
        errors.push(
          problem(
            label,
            key,
            `placeholders do not match en (${formatSetDiff(got, want) || "different"})`,
          ),
        );
      }
    }
    if ((id === "commands" || id.startsWith("bot/")) && !sourcePlural) {
      for (const ch of ["*", "`"]) {
        const want = countChar(source, ch);
        const got = countChar(theirs, ch);
        if (want !== got) {
          errors.push(problem(label, key, `"${ch}" count ${got} does not match en (${want})`));
        }
      }
    }
  };

  for (const [id, messages] of sourceFiles) {
    const label = `${SOURCE}/${id}`;
    if (!isPlain(messages)) {
      errors.push(problem(label, "", "must be an object"));
      continue;
    }
    for (const key of Object.keys(messages)) {
      checkValue(label, id, key, SOURCE, messages[key], messages[key]);
    }
  }

  for (const locale of localeEntries(catalog)) {
    if (locale.code === SOURCE) continue;
    const files = fileMap(bundles[locale.code]);
    for (const [id, messages] of sourceFiles) {
      const label = `${locale.code}/${id}`;
      if (!isPlain(messages)) continue;
      const theirs = files.get(id);
      if (theirs === undefined) {
        if (locale.required) errors.push(problem(label, "", "missing file"));
        continue;
      }
      if (!isPlain(theirs)) {
        errors.push(problem(label, "", "must be an object"));
        continue;
      }
      for (const key of Object.keys(messages)) {
        if (!Object.hasOwn(theirs, key)) {
          if (locale.required) errors.push(problem(label, key, "missing key"));
          else warnings.push(problem(label, key, "untranslated"));
          continue;
        }
        checkValue(label, id, key, locale.code, theirs[key], messages[key]);
        compareValue(label, id, key, messages[key], theirs[key]);
      }
      for (const key of Object.keys(theirs)) {
        if (!Object.hasOwn(messages, key)) errors.push(problem(label, key, "extra key"));
      }
    }
    for (const [id, extra] of files) {
      if (sourceFiles.has(id)) continue;
      const label = `${locale.code}/${id}`;
      if (!isPlain(extra)) {
        errors.push(problem(label, "", "must be an object"));
        continue;
      }
      const keys = Object.keys(extra);
      if (keys.length === 0) errors.push(problem(label, "", "file is not in en"));
      for (const key of keys) errors.push(problem(label, key, "extra key"));
    }
  }
}

export function validate(catalog) {
  const errors = [];
  const warnings = [];
  const input = catalog || {};
  errors.push(...validateLocales(input.locales));
  errors.push(...validateNotes(input.notes, input.bundles || {}));
  errors.push(...validateReview(input.review));
  errors.push(...scanRaw(input.rawTexts || {}));
  validateBundle(input, errors, warnings);
  return { errors, warnings };
}

function findHtmlKeys(root) {
  const dir = join(root, "views");
  const keys = new Set();
  if (!existsSync(dir)) return [];
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(".ejs")) continue;
    const text = readFileSync(join(dir, name), "utf8");
    for (const match of text.matchAll(/data-i18n-html\s*=\s*"([^"]+)"/g)) keys.add(match[1]);
    for (const match of text.matchAll(/data-i18n-html\s*=\s*'([^']+)'/g)) keys.add(match[1]);
  }
  return [...keys];
}

function readJsonFile(abs, label, rawTexts, errors, required) {
  if (!existsSync(abs)) {
    if (required) errors.push(problem(label, "", "missing file"));
    return undefined;
  }
  const text = readFileSync(abs, "utf8");
  try {
    const value = JSON.parse(text);
    rawTexts[label] = text;
    return value;
  } catch (error) {
    errors.push(problem(label, "", `invalid JSON (${error.message})`));
    return undefined;
  }
}

export function loadCatalog(root) {
  const errors = [];
  const rawTexts = {};
  const i18nDir = join(root, "i18n");
  const empty = {
    locales: [],
    bundles: {},
    notes: {},
    review: {},
    htmlKeys: [],
    rawTexts,
  };
  if (!existsSync(i18nDir)) {
    errors.push(problem("i18n", "", "missing directory"));
    return { catalog: empty, errors };
  }
  const locales = readJsonFile(
    join(i18nDir, "locales.json"),
    "locales.json",
    rawTexts,
    errors,
    true,
  );
  const notes = readJsonFile(join(i18nDir, "notes.json"), "notes.json", rawTexts, errors, true);
  const review = readJsonFile(join(i18nDir, "review.json"), "review.json", rawTexts, errors, true);
  const bundles = {};
  const codes = Array.isArray(locales) ? locales.map((locale) => locale?.code) : [];
  const known = new Set(codes);
  if (existsSync(i18nDir)) {
    for (const name of readdirSync(i18nDir)) {
      const abs = join(i18nDir, name);
      if (!statSync(abs).isDirectory()) continue;
      if (!known.has(name)) {
        errors.push(problem(`${name}/`, "", "locale folder is not in locales.json"));
        continue;
      }
      const bundle = {};
      for (const filename of FILE_ORDER) {
        const value = readJsonFile(
          join(abs, `${filename}.json`),
          `${name}/${filename}.json`,
          rawTexts,
          errors,
          false,
        );
        if (value === undefined) continue;
        if (!isPlain(value)) {
          errors.push(problem(`${name}/${filename}.json`, "", "must be an object"));
          continue;
        }
        bundle[filename] = value;
      }
      const botDir = join(abs, "bot");
      if (existsSync(botDir) && statSync(botDir).isDirectory()) {
        bundle.bot = {};
        for (const filename of readdirSync(botDir).sort()) {
          if (!filename.endsWith(".json")) continue;
          const area = filename.slice(0, -5);
          const value = readJsonFile(
            join(botDir, filename),
            `${name}/bot/${filename}`,
            rawTexts,
            errors,
            false,
          );
          if (!isPlain(value)) {
            errors.push(problem(`${name}/bot/${filename}`, "", "must be an object"));
            continue;
          }
          bundle.bot[area] = value;
        }
      }
      for (const filename of readdirSync(abs)) {
        if (filename === "bot") continue;
        if (filename.endsWith(".json") && !FILE_ORDER.includes(filename.slice(0, -5))) {
          errors.push(problem(`${name}/${filename}`, "", "unknown catalog file"));
        }
      }
      bundles[name] = bundle;
    }
  }
  return {
    catalog: {
      locales: Array.isArray(locales) ? locales : [],
      bundles,
      notes: isPlain(notes) ? notes : {},
      review: isPlain(review) ? review : {},
      htmlKeys: findHtmlKeys(root),
      rawTexts,
    },
    errors,
  };
}

export function diffGenerated(catalog, read) {
  const errors = [];
  let expected;
  try {
    expected = renderGenerated(catalog, read("public/gateway-i18n.js"));
  } catch (error) {
    errors.push(problem("public/gateway-i18n.js", "", error.message));
    return errors;
  }
  for (const [rel, text] of Object.entries(expected)) {
    if (read(rel) !== text) errors.push(problem(rel, "", "generated output differs"));
  }
  return errors;
}

function reviewRel(key) {
  const slash = key.indexOf("/");
  if (slash <= 0) return null;
  const code = key.slice(0, slash);
  const file = key.slice(slash + 1);
  if (!code || !file || file.includes("..") || code.includes("..")) return null;
  return join("i18n", code, `${file}.json`);
}

export function reviewMismatches(root, catalog) {
  const lines = [];
  if (!isPlain(catalog.review)) return lines;
  for (const [key, entry] of Object.entries(catalog.review)) {
    if (!isPlain(entry) || typeof entry.sha256 !== "string") continue;
    const rel = reviewRel(key);
    if (!rel) continue;
    const abs = join(root, rel);
    if (!existsSync(abs)) {
      lines.push(`review ${key}: sha256 does not match the file`);
      continue;
    }
    const hash = createHash("sha256").update(readFileSync(abs)).digest("hex");
    if (hash !== entry.sha256.toLowerCase()) {
      lines.push(`review ${key}: sha256 does not match the file`);
    }
  }
  return lines;
}

function readOptional(root, rel) {
  const abs = join(root, rel);
  if (!existsSync(abs)) return null;
  return readFileSync(abs, "utf8");
}

function repoRoot() {
  return join(dirname(fileURLToPath(import.meta.url)), "..");
}

function build(root) {
  const { catalog, errors } = loadCatalog(root);
  if (errors.length) {
    for (const error of errors) console.error(error.message);
    return 1;
  }
  let files;
  try {
    files = renderGenerated(catalog, readOptional(root, "public/gateway-i18n.js"));
  } catch (error) {
    console.error(error.message);
    return 1;
  }
  for (const [rel, text] of Object.entries(files)) {
    const abs = join(root, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
  }
  return 0;
}

function check(root) {
  const { catalog, errors: loadErrors } = loadCatalog(root);
  const result = validate(catalog);
  const drift = diffGenerated(catalog, (rel) => readOptional(root, rel));
  const errors = [...loadErrors, ...result.errors, ...drift];
  for (const warning of result.warnings) console.log(warning.message);
  for (const line of reviewMismatches(root, catalog)) console.log(line);
  if (errors.length) {
    console.error(`i18n check failed (${errors.length})`);
    for (const error of errors) console.error(error.message);
    return 1;
  }
  console.log("i18n check passed");
  return 0;
}

function main() {
  const command = process.argv[2];
  if (command !== "build" && command !== "check") {
    console.error("Usage: node scripts/i18n.mjs build | check");
    process.exit(1);
  }
  process.exit(command === "build" ? build(repoRoot()) : check(repoRoot()));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
